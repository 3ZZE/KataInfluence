class GracefulTerm:
    """Turn SIGTERM into KeyboardInterrupt so it follows the Ctrl-C path."""

    def __enter__(self):
        self.old = signal.signal(signal.SIGTERM, self._h)

    def _h(self, *_):
        raise KeyboardInterrupt

    def __exit__(self, *_):
        signal.signal(signal.SIGTERM, self.old)


def cmd_run(args):
    if args.games < 2 or args.games % 2:
        die("--games must be even (colours are balanced)")
    if not os.access(args.katago, os.X_OK):
        die(f"katago binary not found: {args.katago}")
    rng = random.Random(args.seed)
    deadline = time.time() + args.minutes * 60 if args.minutes else None
    work_root = args.work_dir or os.path.splitext(os.path.abspath(args.state))[0] + "_work"
    with state_lock(args.state), GracefulTerm():
        st = load_state(args.state)
        pool_name, pool = get_pool(st, args, create=True)
        batch_no = 0
        while True:
            if args.batches is not None and batch_no >= args.batches:
                break
            if deadline is not None and time.time() >= deadline:
                log("time limit reached")
                break
            if args.batches is None and deadline is None and batch_no >= 1:
                break  # neither limit given: one batch
            nets = discover_nets(args.models_dir)  # pick up new nets every batch
            register_nets(st, nets)
            cand = [n["name"] for n in select_nets(st, nets, args)]
            if len(cand) < 2:
                die("fewer than 2 nets selected")
            F = fit_pool(st, pool, args, extra_names=cand)
            a, b, why = choose_pair(st, pool, cand, F, rng, args.window)
            ea, eb = F["elo"][F["idx"][a]], F["elo"][F["idx"][b]]
            log(f"batch {batch_no + 1}: {short_name(st, a)} ({ea:+.0f}) vs "
                f"{short_name(st, b)} ({eb:+.0f}), {args.games} games [{why}]")
            if args.dry_run:
                batch_no += 1
                continue
            stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
            bdir = os.path.join(work_root, pool_name,
                                f"{stamp}_{short_name(st, a)}_vs_{short_name(st, b)}")
            t0 = time.time()
            netinfo = {n: {"name": n, "path": st["nets"][n]["path"]} for n in (a, b)}
            games, interrupted = run_batch(args, pool["settings"], netinfo[a], netinfo[b], bdir)
            n = record_games(pool, games, {a, b}, bdir)
            if pool.get("anchor") is None and n["games"]:
                pool["anchor"] = args.anchor or F["names"][0]
            pool["batches"].append({"time": stamp, "a": a, "b": b, "games": n["games"],
                                    "a_score": sum(1 for g in games if g[2] and
                                                   (g[0] if g[2] == "B" else g[1]) == a)
                                    + 0.5 * n["draw"],
                                    "seconds": round(time.time() - t0), "dir": bdir,
                                    "partial": interrupted})
            save_state(st, args.state)
            batch_no += 1
            rec = pool["pairs"].get(pair_key(a, b))
            g, s = pair_totals(rec) if rec else (0, 0)
            s_a = s if rec and rec["a"] == a else g - s
            log(f"  recorded {n['games']} games in {time.time() - t0:.0f}s "
                f"(B wins {n['B']}, W wins {n['W']}, draws {n['draw']}); "
                f"pair total {short_name(st, a)} {s_a:g}/{g}")
            if interrupted:
                log("stopped by interrupt; state is consistent")
                break
        F = fit_pool(st, pool, args)
        if F and not args.dry_run:
            print_table(st, pool, F, only=None)


def cmd_import(args):
    with state_lock(args.state):
        st = load_state(args.state)
        nets = discover_nets(args.models_dir)
        register_nets(st, nets)
        by_name = {}
        for n in st["nets"]:
            by_name[n] = n
            for alias in net_aliases(st, n):
                by_name.setdefault(alias, n)
        pool_name, pool = get_pool(st, args, create=True)
        settings = pool["settings"]
        seen = set(st["imported_files"])
        total = 0
        files = []
        for d in args.dirs:
            files += sorted(glob.glob(os.path.join(d, "*.sgf*"))) if os.path.isdir(d) else [d]
        for f in files:
            data = open(f, "rb").read()
            h = hashlib.sha1(data).hexdigest()
            if h in seen:
                print(f"skip (already imported): {f}")
                continue
            games = list(parse_sgf_games(data.decode(errors="replace")))
            bad = None
            for black, white, _, ru, vis in games:
                if black not in by_name or white not in by_name:
                    bad = f"unknown bot name {black} / {white}"
                elif by_name[black] == by_name[white]:
                    bad = "same net on both sides (visit ladder?)"
                elif f"maxmoves{settings['maxTurns']}" not in ru:
                    bad = f"ruleset {ru!r} does not match maxTurns={settings['maxTurns']}"
                elif vis is not None and vis > settings["maxVisits"]:
                    bad = f"search with {vis} visits > maxVisits={settings['maxVisits']}"
                if bad:
                    break
            if bad:
                print(f"skip {f}: {bad}")
                continue
            for black, white, winner, _, _ in games:
                add_game(pool, by_name[black], by_name[white], winner)
            total += len(games)
            seen.add(h)
            st["imported_files"].append(h)
        if pool.get("anchor") is None and total:
            F = fit_pool(st, pool, args)
            pool["anchor"] = F["anchor"]
        pool["batches"].append({"time": datetime.datetime.now().strftime("%Y%m%d-%H%M%S"),
                                "import": [os.path.abspath(d) for d in args.dirs], "games": total})
        if not args.dry_run:
            save_state(st, args.state)
        print(f"imported {total} games into pool '{pool_name}'" + (" (dry run, not saved)" if args.dry_run else ""))


def print_table(st, pool, F, only=None):
    recs = net_record(pool)
    w_net = max([30] + [len(n) + 1 for n in F["names"]])
    print(f"{'net':<{w_net}} {'samples':>8} {'Elo':>7} {'±err':>6} {'local':>6} {'games':>6} {'W-D-L':>14} {'score':>6}")
    for i, n in enumerate(F["names"]):
        if only is not None and n not in only:
            continue
        w, d, l, g = recs.get(n, [0, 0, 0, 0])
        mark = " *" if n == F["anchor"] else ""
        score = f"{100 * (w + d / 2) / g:5.1f}%" if g else "     -"
        print(f"{n:<{w_net}} {fmt_samples(net_samples(n)):>8} {F['elo'][i]:+7.0f} "
              f"{F['err'][i]:6.0f} {F['local_err'][i]:6.0f} {g:6d} {f'{w}-{d}-{l}':>14} {score}{mark}")
    print("Elo relative to anchor (*); ±err = 1 s.d. vs anchor; local = 1 s.d. from own games+prior "
          "(used for pairing).")


def cmd_status(args):
    st = load_state(args.state)
    pool_name, pool = get_pool(st, args, create=False)
    F = fit_pool(st, pool, args)
    if F is None:
        print(f"pool '{pool_name}': no games yet")
        return
    total = sum(pair_totals(r)[0] for r in pool["pairs"].values())
    multi = len({net_arch(n) for n in F["names"]}) > 1
    print(f"pool '{pool_name}' {pool['settings']}: {total} games, {len(pool['pairs'])} pairs, "
          f"prior {args.prior_draws:g} virtual draws between consecutive nets"
          + (" of the same arch" if multi else ""))
    print_table(st, pool, F)
    if args.pairs:
        key = net_order(st)
        recs = sorted(pool["pairs"].values(), key=lambda r: (key(r["a"]), key(r["b"])))
        labels = [f"{short_name(st, r['a'])} vs {short_name(st, r['b'])}" for r in recs]
        w_pair = max([26] + [len(x) + 1 for x in labels])
        print(f"\n{'pair':<{w_pair}} {'games':>6} {'score of 1st':>13} {'1st as B (W-D-L)':>17} {'1st as W':>10}")
        for rec, label in zip(recs, labels):
            g, s = pair_totals(rec)
            print(f"{label:<{w_pair}} {g:6d} {100 * s / g:12.1f}% "
                  f"{'-'.join(map(str, rec['a_black'])):>17} {'-'.join(map(str, rec['a_white'])):>10}")


def cmd_plot(args):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    st = load_state(args.state)
    pool_name, pool = get_pool(st, args, create=False)
    F = fit_pool(st, pool, args)
    if F is None:
        die("no games to plot")
    names = F["names"]
    arch = np.array([net_arch(n) for n in names])
    archs = list(dict.fromkeys(arch))  # net_order: primary arch first
    multi = len(archs) > 1
    x = np.array([net_samples(n) / 1e6 for n in names])
    y, e, g = F["elo"], F["err"], F["games"]
    played = g > 0
    ink, muted, grid = "#0b0b0b", "#52514e", "#e6e5e0"
    # Categorical slots in fixed order, one per arch.
    palette = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]
    fig, ax = plt.subplots(figsize=(10, 5.5), dpi=120)
    for c, a in enumerate(archs):
        series = palette[c % len(palette)]
        m = arch == a
        pm, um = m & played, m & ~played
        ax.plot(x[m], y[m], color=series, lw=2, zorder=2)
        ax.errorbar(x[pm], y[pm], yerr=e[pm], fmt="o", ms=5, color=series, ecolor=series,
                    elinewidth=1.2, capsize=0, zorder=3,
                    label=f"{a}: Elo ± 1 s.d. (vs anchor)" if multi else "Elo ± 1 s.d. (vs anchor)")
        if um.any():
            ax.plot(x[um], y[um], "o", ms=5, mfc="white", mec=series, zorder=3,
                    label=f"{a}: no games yet (prior only)" if multi else "no games yet (prior only)")
        # Direct label the newest net of each arch.
        last = np.flatnonzero(m)[-1]
        ax.annotate(f"{a} {y[last]:+.0f}" if multi else f"{y[last]:+.0f}", (x[last], y[last]),
                    xytext=(6, 0), textcoords="offset points", va="center", color=ink, fontsize=9)
    ax.set_xlabel("training samples of each arch (millions)" if multi else "training samples (millions)",
                  color=muted)
    if (e[played] > 800).any():
        # A net with few one-sided games (e.g. a new arch's first 0-32) has a huge
        # error bar; keep the y range on the ratings instead.
        lo, hi = (y - np.minimum(e, 800)).min(), (y + np.minimum(e, 800)).max()
        ax.set_ylim(lo - 0.05 * (hi - lo), hi + 0.05 * (hi - lo))
    ax.set_ylabel("Elo", color=muted)
    total = int(g.sum() / 2)
    ax.set_title(f"Influence net strength, pool {pool_name} ({pool['settings']['maxVisits']} visits), "
                 f"{total} games", color=ink, loc="left")
    ax.grid(True, color=grid, lw=0.8)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(grid)
    ax.tick_params(colors=muted)
    ax.legend(frameon=False, loc="lower right", labelcolor=muted)
    fig.tight_layout()
    out = args.out or os.path.splitext(os.path.abspath(args.state))[0] + f"_{pool_name}.png"
    fig.savefig(out)
    print(f"wrote {out}")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--state", default=DEFAULT_STATE, help="state JSON (default: %(default)s)")
    common.add_argument("--models-dir", default=DEFAULT_MODELS)
    common.add_argument("--visits", type=int, default=16, help="maxVisits per move (selects the pool)")
    common.add_argument("--max-turns", type=int, default=180, help="Influence maxTurns (selects the pool)")
    common.add_argument("--pool", default=None, help="pool name (default: v<visits>)")
    common.add_argument("--prior-draws", type=float, default=2.0,
                        help="virtual draws between consecutive nets (default %(default)s)")
    common.add_argument("--anchor", default=None, help="net name fixed at Elo 0 (default: oldest rated net)")
