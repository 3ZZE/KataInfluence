#!/usr/bin/env python3
"""Persistent strength rating for Influence nets (Bradley-Terry / Bayesian Elo).

Ideas taken from katago-server (src/apps/trainings/services/bayesian_elo.py and
src/apps/distributed_efforts/services/rating_network_pairer.py):
  * every net gets a weak prior of `--prior-draws` virtual draws against the
    previous net (by training samples) of the same architecture (the name before
    `-s<samples>-d<rows>`), so a fresh net starts at its predecessor's rating;
    architectures are linked only by real games and a tiny all-pairs prior;
  * draws count as half a win;
  * pairing picks a "reference" net (highest uncertainty / fewest games / highest
    upper confidence) and an opponent of similar strength, weighted by the
    variance p*(1-p) of the predicted game result.
Unlike katago-server the fit is a full Newton solve and errors come from the full
inverse Fisher information (i.e. they are uncertainties relative to the anchor).

See README.md in this directory for usage.
"""

