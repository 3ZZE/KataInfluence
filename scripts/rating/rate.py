def discover_nets(models_dir):
    nets = []
    for p in glob.glob(os.path.join(models_dir, "*.bin.gz")):
        m = NET_RE.match(os.path.basename(p))
        if m:
            nets.append({"name": m["name"], "samples": int(m["samples"]), "path": os.path.abspath(p)})
    nets.sort(key=lambda n: (net_arch(n["name"]), n["samples"]))
    return nets


def select_nets(st, nets, args):
    """Selected nets, sorted by net_order (primary arch first, then by samples)."""
    sel = [n for n in nets if n["samples"] >= args.min_samples
           and (args.max_samples is None or n["samples"] <= args.max_samples)]
    if args.every > 1 and sel:
        # Keep every k-th net counting back from the newest of each arch, so the
        # latest of each arch is always in.
        by_arch = {}
        for n in sel:
            by_arch.setdefault(net_arch(n["name"]), []).append(n)
        sel = [n for group in by_arch.values()
               for n in sorted(group, key=lambda n: n["samples"])[::-1][::args.every]]
    if args.nets:
        want = set(args.nets.split(","))
        sel = [n for n in nets if want & net_aliases(st, n["name"])]
        known = set().union(*(net_aliases(st, n["name"]) for n in nets)) if nets else set()
        if want - known:
            die(f"--nets: unknown net(s) {', '.join(sorted(want - known))}")
    key = net_order(st)
    return sorted(sel, key=lambda n: key(n["name"]))


def net_arch(name):
    m = ARCH_RE.match(name)
    return m["arch"] if m else name


def net_samples(name):
    m = ARCH_RE.match(name)
    return int(m["samples"]) if m else 0


def primary_arch(st):
    """The architecture with the most known nets (ties: alphabetically first)."""
    counts = {}
    for n in st["nets"]:
        counts[net_arch(n)] = counts.get(net_arch(n), 0) + 1
    return min(counts, key=lambda a: (-counts[a], a)) if counts else None


def net_order(st):
    """Sort key for net names: primary arch first, then by arch, then by samples."""
    prim = primary_arch(st)
    return lambda n: (net_arch(n) != prim, net_arch(n), net_samples(n), n)


def short_name(st, name):
    """s49733k for the primary arch, b10c256nbt-s15000k for the others."""
    s = f"s{round(net_samples(name) / 1000)}k"
    return s if net_arch(name) == primary_arch(st) else f"{net_arch(name)}-{s}"


def net_aliases(st, name):
    """Names accepted for a net: full name, short name and arch-prefixed short name."""
    s = f"s{round(net_samples(name) / 1000)}k"
    return {name, short_name(st, name), f"{net_arch(name)}-{s}"}


def fmt_samples(samples):
    return f"{samples / 1e6:.2f}M"


# ----------------------------------------------------------------------------
# Rating fit
# ----------------------------------------------------------------------------

def pair_totals(rec):
    """(games, score of a) with draws = half."""
    w = rec["a_black"][0] + rec["a_white"][0]
    d = rec["a_black"][1] + rec["a_white"][1]
    l = rec["a_black"][2] + rec["a_white"][2]
    return w + d + l, w + 0.5 * d


def net_record(pool):
    """name -> [wins, draws, losses, games] from real games."""
    out = {}
    for rec in pool["pairs"].values():
        wa = rec["a_black"][0] + rec["a_white"][0]
        d = rec["a_black"][1] + rec["a_white"][1]
        la = rec["a_black"][2] + rec["a_white"][2]
        for name, (w, l) in ((rec["a"], (wa, la)), (rec["b"], (la, wa))):
            r = out.setdefault(name, [0, 0, 0, 0])
            r[0] += w
            r[1] += d
            r[2] += l
            r[3] += w + d + l
    return out


def fit(st, pool, extra_names=(), prior_draws=2.0, anchor=None):
    """Bradley-Terry MAP fit. Returns dict with names (sorted by net_order) and
    elo, err (vs anchor, full covariance), local_err (1/sqrt(own precision)),
    games, and the anchor name."""
    names = set(extra_names)
    for rec in pool["pairs"].values():
        if pair_totals(rec)[0] > 0:
            names.add(rec["a"])
            names.add(rec["b"])
    names = sorted(names, key=net_order(st))
    k = len(names)
    if k == 0:
        return None
    idx = {n: i for i, n in enumerate(names)}
    N = np.zeros((k, k))
    S = np.zeros((k, k))  # S[i,j] = score of i against j
    for rec in pool["pairs"].values():
        g, s = pair_totals(rec)
        if g == 0:
            continue
        i, j = idx[rec["a"]], idx[rec["b"]]
        N[i, j] += g
        N[j, i] += g
        S[i, j] += s
        S[j, i] += g - s
    real_games = N.sum(axis=1)
    # Prior: virtual draws between consecutive nets (by training samples) of the
    # same arch. Different archs are linked only by real games and the tiny prior.
    arch = [net_arch(n) for n in names]
    for i in range(k - 1):
        if arch[i] != arch[i + 1]:
            continue
        N[i, i + 1] += prior_draws
        N[i + 1, i] += prior_draws
        S[i, i + 1] += prior_draws / 2
        S[i + 1, i] += prior_draws / 2
    # Tiny all-pairs prior (like katago-server's 0.01 for orphan nets) keeps the
    # Hessian invertible even with --prior-draws 0, and gives the first net of a
    # new arch, before it has games, a finite rating near the pool average.
    eps = 0.01 / max(k - 1, 1)
    N += eps * (1 - np.eye(k))
    S += 0.5 * eps * (1 - np.eye(k))

    if anchor not in idx:
        anchor = names[0]
    a = idx[anchor]
    free = np.array([i for i in range(k) if i != a], dtype=int)
    r = np.zeros(k)

    def hessian_neg(p):
        W = N * p * (1 - p)
        return np.diag(W.sum(axis=1)) - W

    for _ in range(200):
        p = 1.0 / (1.0 + np.exp(-(r[:, None] - r[None, :])))
        g = (S - N * p).sum(axis=1)
        if len(free) == 0:
            break
        H = hessian_neg(p)[np.ix_(free, free)]
        step = np.linalg.solve(H, g[free])
        m = np.max(np.abs(step))
        if m > 1.0:  # damp big steps; the log-likelihood is concave
            step *= 1.0 / m
        r[free] += step
        if m < 1e-10:
            break
    p = 1.0 / (1.0 + np.exp(-(r[:, None] - r[None, :])))
    Hfull = hessian_neg(p)
    err = np.zeros(k)
    if len(free):
        cov = np.linalg.inv(Hfull[np.ix_(free, free)])
        err[free] = np.sqrt(np.maximum(np.diag(cov), 0))
    local_err = 1.0 / np.sqrt(np.maximum(np.diag(Hfull), 1e-12))
    return {
        "names": names,
        "idx": idx,
        "elo": r * ELO_PER_NAT,
        "err": err * ELO_PER_NAT,
        "local_err": np.minimum(local_err * ELO_PER_NAT, 2000.0),
        "games": real_games,
        "anchor": anchor,
    }


def fit_pool(st, pool, args, extra_names=()):
    return fit(st, pool, extra_names, prior_draws=args.prior_draws, anchor=args.anchor or pool.get("anchor"))


# ----------------------------------------------------------------------------
# Pairing
# ----------------------------------------------------------------------------

def pair_games(pool, a, b):
    rec = pool["pairs"].get(pair_key(a, b))
    return pair_totals(rec)[0] if rec else 0


def choose_pair(st, pool, cand, F, rng, window):
    """cand: names eligible to play (sorted by net_order, len >= 2)."""
    idx = F["idx"]
    elo = {n: F["elo"][idx[n]] for n in cand}
    lerr = {n: F["local_err"][idx[n]] for n in cand}
    games = {n: F["games"][idx[n]] for n in cand}

    def weighted_top(items, key, top=5):
        items = sorted(items, key=key)[:top]
        weights = [1.0 / (i + 1) for i in range(len(items))]
        return rng.choices(items, weights=weights)[0]

    # 1) Nets that never played: play their neighbour in training order (same
    #    arch), preferring a neighbour that already has games (anchors the new
    #    net). If no neighbour of its arch has games, the first net of a new arch
    #    plays the newest primary-arch net instead.
    fresh = [n for n in cand if games[n] == 0]
    if fresh:
        ref = fresh[-1]  # newest first (of the last arch)
        i = cand.index(ref)
        nbrs = [cand[j] for j in (i - 1, i + 1)
                if 0 <= j < len(cand) and net_arch(cand[j]) == net_arch(ref)]
        prim = [n for n in cand if net_arch(n) == primary_arch(st)]
        if not any(games[n] for n in nbrs) and prim and net_arch(ref) != primary_arch(st):
            opp = max(prim, key=lambda n: (games[n] > 0, net_samples(n)))
            return ref, opp, "new arch net vs newest primary-arch net"
        if not nbrs:  # no neighbour of its arch selected: nearest rated net
            nbrs = [n for n in cand if n != ref]
        nbrs.sort(key=lambda n: (games[n] == 0, abs(elo[n] - elo[ref])))
        return ref, nbrs[0], "new net vs training neighbour"

    # 2) Reference net, katago-server style: high uncertainty / low data / high upper bound.
    mode = rng.choice(["uncertainty", "lowdata", "top"])
    if mode == "uncertainty":
        ref = weighted_top(cand, key=lambda n: -lerr[n])
    elif mode == "lowdata":
        ref = weighted_top(cand, key=lambda n: games[n])
    else:
        ref = weighted_top(cand, key=lambda n: -(elo[n] + lerr[n]))

    # 3) Opponent of similar strength. Jitter the reference rating by its
    #    uncertainty so uncertain nets meet a wider range of opponents.
    target = elo[ref] + rng.gauss(0, 1) * lerr[ref]
    others = [n for n in cand if n != ref]
    near = [n for n in others if abs(elo[n] - target) <= window]
    if len(near) < 2:
        weaker = sorted([n for n in others if elo[n] <= target], key=lambda n: -elo[n])[:2]
        stronger = sorted([n for n in others if elo[n] > target], key=lambda n: elo[n])[:2]
        near = weaker + stronger
        opp = rng.choice(near)
    else:
        w = []
        for n in near:
            q = 1.0 / (1.0 + math.exp(-(elo[n] - target) / ELO_PER_NAT))
            # p(1-p): most informative games; mild penalty for pairs already played a lot
            w.append(q * (1 - q) / math.sqrt(1.0 + pair_games(pool, ref, n) / 64.0))
        opp = rng.choices(near, weights=w)[0]
    return ref, opp, f"{mode}: gap {elo[opp] - elo[ref]:+.0f} Elo"


