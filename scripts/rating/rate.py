def _set_pdeathsig():
    """Linux: SIGTERM the child if this python process dies."""
    try:
        import ctypes
        ctypes.CDLL("libc.so.6", use_errno=True).prctl(1, signal.SIGTERM)  # PR_SET_PDEATHSIG
    except Exception:
        pass


def run_batch(args, settings, net_a, net_b, batch_dir):
    """Run one katago match between two nets. Returns (games, interrupted).

    katago is started in its own session so a terminal Ctrl-C only reaches this
    script, which forwards SIGINT to exactly that PID. katago then drops the
    unfinished games and only the finished ones are in the SGFs.
    """
    os.makedirs(batch_dir, exist_ok=True)
    sgf_dir = os.path.join(batch_dir, "sgfs")
    cfg_path = os.path.join(batch_dir, "match.cfg")
    threads = min(args.games, args.threads)
    with open(cfg_path, "w") as f:
        f.write(CONFIG_TEMPLATE.format(
            bot0=net_a["name"], model0=net_a["path"], bot1=net_b["name"], model1=net_b["path"],
            games=args.games, threads=threads, **settings))
    cmd = [args.katago, "match", "-config", cfg_path, "-log-file", os.path.join(batch_dir, "match.log"),
           "-sgf-output-dir", sgf_dir]
    out = open(os.path.join(batch_dir, "stdout.txt"), "w")
    proc = subprocess.Popen(cmd, cwd=batch_dir, stdout=out, stderr=subprocess.STDOUT,
                            start_new_session=True, preexec_fn=_set_pdeathsig)
    interrupted = False
    last_done = -1
    t0 = time.time()
    try:
        while proc.poll() is None:
            time.sleep(2)
            done = sum(open(f, errors="replace").read().count("RE[")
                       for f in glob.glob(os.path.join(sgf_dir, "*.sgfs")))
            if done != last_done and sys.stdout.isatty():
                print(f"\r  {done}/{args.games} games, {time.time() - t0:.0f}s", end="", flush=True)
                last_done = done
    except KeyboardInterrupt:
        interrupted = True
        print()
        log(f"interrupt: stopping katago (pid {proc.pid}), keeping finished games... (Ctrl-C again to kill)")
        try:
            proc.send_signal(signal.SIGINT)
            proc.wait(timeout=120)
        except (KeyboardInterrupt, subprocess.TimeoutExpired):
            proc.kill()
            proc.wait()
    finally:
        out.close()
    if sys.stdout.isatty():
        print()
    if proc.returncode not in (0, None) and not interrupted:
        tail = open(os.path.join(batch_dir, "stdout.txt"), errors="replace").read()[-2000:]
        raise RuntimeError(f"katago exited with code {proc.returncode}; see {batch_dir}\n{tail}")
    return read_sgf_dir(sgf_dir), interrupted


def record_games(pool, games, valid_names, source):
    n = {"games": 0, "B": 0, "W": 0, "draw": 0}
    for black, white, winner, _, _ in games:
        if black not in valid_names or white not in valid_names or black == white:
            raise ValueError(f"unexpected players {black} vs {white}")
        add_game(pool, black, white, winner)
        n["games"] += 1
        n["draw" if winner is None else winner] += 1
    return n


