def empty_state():
    return {"version": STATE_VERSION, "nets": {}, "pools": {}, "imported_files": []}


def load_state(path):
    if not os.path.exists(path):
        return empty_state()
    with open(path) as f:
        st = json.load(f)
    if st.get("version") != STATE_VERSION:
        die(f"{path}: unsupported state version {st.get('version')}")
    return st


def save_state(st, path):
    """Atomic write: temp file in the same dir, fsync, rename."""
    d = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".rating_state.", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w") as f:
            json.dump(st, f, indent=1, sort_keys=True)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


@contextlib.contextmanager
def state_lock(path):
    """Prevent two writers (run/import) on the same state file."""
    lockpath = os.path.abspath(path) + ".lock"
    os.makedirs(os.path.dirname(lockpath), exist_ok=True)
    with open(lockpath, "w") as f:
        try:
            fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            die(f"{path} is locked by another rate.py process")
        yield


def pool_settings(args):
    return {
        "maxVisits": int(args.visits),
        "maxTurns": int(args.max_turns),
        "chosenMoveTemperatureEarly": 0.6,
        "chosenMoveTemperature": 0.2,
    }


def default_pool_name(settings):
    name = f"v{settings['maxVisits']}"
    if settings["maxTurns"] != 180:
        name += f"-t{settings['maxTurns']}"
    return name


def get_pool(st, args, create):
    """Return (name, pool). Refuses to mix games with different settings."""
    settings = pool_settings(args)
    name = args.pool or default_pool_name(settings)
    pool = st["pools"].get(name)
    if pool is None:
        if not create:
            die(f"no pool '{name}' in state (pools: {', '.join(st['pools']) or 'none'})")
        pool = {"settings": settings, "anchor": None, "pairs": {}, "batches": []}
        st["pools"][name] = pool
    elif create and pool["settings"] != settings:
        die(f"pool '{name}' has settings {pool['settings']}, requested {settings}; "
            f"use another --pool name")
    return name, pool


def pair_key(a, b):
    return f"{a}|{b}" if a < b else f"{b}|{a}"


def add_game(pool, black, white, winner):
    """winner: 'B', 'W' or None (draw / no result).

    Per pair (a<b), stored from a's point of view:
      a_black = [wins, draws, losses] with a as Black, a_white likewise.
    """
    a, b = sorted((black, white))
    rec = pool["pairs"].setdefault(pair_key(a, b), {"a": a, "b": b, "a_black": [0, 0, 0], "a_white": [0, 0, 0]})
    side = "a_black" if black == a else "a_white"
    a_color = "B" if black == a else "W"
    idx = 1 if winner is None else (0 if winner == a_color else 2)
    rec[side][idx] += 1


def register_nets(st, nets):
    for n in nets:
        st["nets"].setdefault(n["name"], {"samples": n["samples"], "path": n["path"]})
        st["nets"][n["name"]]["path"] = n["path"]


