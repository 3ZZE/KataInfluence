    r = sub.add_parser("run", parents=[common], help="play rating batches")
    r.add_argument("--batches", type=int, default=None, help="number of batches")
    r.add_argument("--minutes", type=float, default=None, help="no new batch after this many minutes")
    r.add_argument("--games", type=int, default=32, help="games per batch, even (default %(default)s)")
    r.add_argument("--threads", type=int, default=64, help="max parallel games (default %(default)s)")
    r.add_argument("--window", type=float, default=200, help="opponent Elo window (default %(default)s)")
    r.add_argument("--min-samples", type=int, default=0)
    r.add_argument("--max-samples", type=int, default=None)
    r.add_argument("--every", type=int, default=1, help="use every k-th net (newest always included)")
    r.add_argument("--nets", default=None,
                   help="comma list of net names or short names (sNNNk, or ARCH-sNNNk for any arch)")
