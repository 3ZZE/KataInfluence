def parse_sgf_games(text):
    """Yield (black, white, winner, ruleset, max_visits) for each complete game."""
    for g in text.split("(;")[1:]:
        g = g.strip()
        if not g.endswith(")"):
            continue  # truncated
        pb = re.search(r"PB\[([^\]]*)\]", g)
        pw = re.search(r"PW\[([^\]]*)\]", g)
        res = re.search(r"RE\[([^\]]*)\]", g)
        if not (pb and pw and res):
            continue
        r = res.group(1)
        winner = r[0] if r.startswith(("B+", "W+")) else None
        ru = re.search(r"RU\[([^\]]*)\]", g)
        vis = [int(v) for v in re.findall(r"\bv=(\d+)", g)]
        yield pb.group(1), pw.group(1), winner, (ru.group(1) if ru else ""), (max(vis) if vis else None)


def read_sgf_dir(d):
    games = []
    for f in sorted(glob.glob(os.path.join(d, "*.sgf*"))):
        with open(f, errors="replace") as fh:
            games.extend(parse_sgf_games(fh.read()))
    return games


